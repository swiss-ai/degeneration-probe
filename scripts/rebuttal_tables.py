def probes_table(table: pd.DataFrame, budget: float, split: str, label: str, caption: str,
                 placeholder: bool = False, legend: bool = True) -> str:
    """The nine reported probes on one split, one column per probe and one row per metric.

    With ``placeholder`` every value is left as a red question mark, for a split whose labels are not in yet.
    Without ``legend`` the caption is only ``caption``, for a table that repeats the layout of another."""
    if legend:
        caption += (rf"""
 FA: realised false-alarm rate on healthy responses, in percent, at the threshold calibrated on validation for $\beta={budget * 100:.0f}\%$. Pre: coverage of the positions before the warning window. Lead: median first alarm minus the onset, in tokens. $n$: number of degenerate responses. Each model has its frozen probe at its selected layer, the adapted probe at the same layer, and the adapted probe at its own selected layer. Mean $\pm$ one standard deviation over three seeds.""")
    s4 = table[table["recipe"].str.startswith("frontier_window W=512 centered K=256")].copy()
    s4["regime"] = np.where(s4["lora"].eq("none"), "frozen", "adapted")
    s4["detection"] = s4["detected_positives"] / (s4["detected_positives"] + s4["never_fired_positives"])
    columns, heads, names = [], [], []
    for model, probes in PROBES.items():
        picked = [s4[(s4["model"] == model) & (s4["regime"] == regime) & (s4["layer"] == layer)
                     & (s4["split"] == split) & np.isclose(s4["target_negative_fpr"], budget)]
                  for regime, layer in probes]
        positives = int(picked[0]["positives"].iloc[0]) if len(picked[0]) else 0
        n = "?" if placeholder else str(positives)
        heads.append(rf"\multicolumn{{3}}{{c}}{{{MODELS[model][1]} ($n={n}$)}}")
        names.append(" & ".join(f"{regime}, L{layer}" for regime, layer in probes))
        columns += picked
    lines = []
    for name, metric, digits, scale in PROBE_ROWS:
        cells = []
        for rows in columns:
            if placeholder:
                cells.append(PLACEHOLDER)
            elif metric == "median_offset":
                cells.append(f"${rows[metric].mean():+.0f} \\pm {rows[metric].std():.0f}$")
            else:
                cells.append(pm(rows[metric].mean() * scale, rows[metric].std() * scale, digits))
        groups = [" & ".join(cells[i:i + 3]) for i in range(0, len(cells), 3)]
        lines.append(f"{name}\n& " + "\n& ".join(groups) + r" \\")
    return rf"""\begin{{table}}[!htbp]
\centering
\caption{{{caption}}}
\label{{{label}}}
\setlength{{\tabcolsep}}{{3pt}}
\resizebox{{\linewidth}}{{!}}{{%
\begin{{tabular}}{{l ccc ccc ccc}}
\toprule
& {chr(10).join("& " + h if i else h for i, h in enumerate(heads))} \\
\cmidrule(lr){{2-4}} \cmidrule(lr){{5-7}} \cmidrule(lr){{8-10}}
& {chr(10).join("& " + n if i else n for i, n in enumerate(names))} \\
\midrule
{chr(10).join(lines)}
\bottomrule
\end{{tabular}}%
}}
\end{{table}}
"""




