SCORER_GROUPS = [
    ("nothing", ["random alarms", "token-cap rule"]),
    ("tokens", ["repeated-n-gram rule", "windowed seq-rep-2", "rep/l"]),
    ("confidence", ["windowed entropy", "windowed -log p"]),
    ("hidden states", ["frozen probe", "adapted probe"]),
]
SCORER_NAMES = {"random alarms": "random alarms", "token-cap rule": "token-cap rule",
                "repeated-n-gram rule": r"repeated-$n$-gram rule", "windowed seq-rep-2": "windowed seq-rep-2",
                "rep/l": r"rep$/\ell$", "windowed entropy": "windowed entropy",
                "windowed -log p": r"\begin{tabular}[t]{@{}l@{}}windowed negative\\ log-probability\end{tabular}",
                "frozen probe": "frozen probe", "adapted probe": "adapted probe"}


def comparison_rows(budget: float, split: str, adapted: str) -> dict:
    """Per model, the Q3 rows keyed by scorer family; ``adapted`` picks the adapted probe at the frozen
    probe's layer ("same") or at its own selected layer ("own")."""
    table = pd.read_csv(ANALYSIS / "q3_comparison.csv")
    table = table[(table["split"] == split) & np.isclose(table["budget"], budget)]
    rows = {}
    for model, probes in PROBES.items():
        part = table[table["model"] == model]
        frozen_layer = probes[0][1]
        adapted_layer = frozen_layer if adapted == "same" else probes[-1][1]
        picked = {}
        for _, row in part.iterrows():
            name = row["scorer"]
            if name.startswith("repeated-n-gram rule"):
                picked["repeated-n-gram rule"] = row
            elif name.startswith("frozen probe"):
                picked["frozen probe"] = row
            elif name == f"adapted probe (L{adapted_layer})":
                picked["adapted probe"] = row
            elif not name.startswith("adapted probe"):
                picked[name] = row
        rows[model] = picked
    return rows


def cell(row, metric: str, digits: int = 3) -> str:
    mean, std = row[metric], row.get(f"{metric}_std")
    if 0 < abs(mean) < 0.0005:
        mantissa, exponent = f"{mean:.0e}".split("e")
        return f"${mantissa}\\times10^{{{int(exponent)}}}$"
    value = small(mean) if digits == 3 else f"{mean:.{digits}f}"
    if pd.isna(std) or row["seeds"] < 2:
        return f"${value}$"
    return f"${value}\\sd{{{std:.{digits}f}}}$"


def comparison_table(budget: float, split: str, label: str, caption: str) -> str:
    """Post-onset coverage, warning coverage and early-warning rate of every scorer, one block per model."""
    rows = comparison_rows(budget, split, "own")
    metrics = ["in_pattern_recall", "warning_recall_256", "fired_before_frontier"]
    lines = []
    for model, picked in rows.items():
        best = {}
        for metric in metrics:
            values = pd.Series({name: row[metric] for name, row in picked.items()}).dropna()
            if metric == "fired_before_frontier":
                values = values[[picked[n]["detection_rate"] >= 0.9 for n in values.index]]
            top = values.idxmax()
            spread = picked[top].get(f"{metric}_std", 0)
            best[metric] = (top, values[top], 0 if pd.isna(spread) else spread)
        if lines:
            lines.append(r"    \midrule")
        first = True
        for g, (_, names) in enumerate(SCORER_GROUPS):
            if g:
                lines.append(r"    \addlinespace[2pt]")
            for name in names:
                row = picked.get(name)
                if row is None:
                    continue
                shown = "windowed negative log-probability" if name == "windowed -log p" else SCORER_NAMES[name]
                cells = [MODELS[model][1] if first else "", shown]
                first = False
                for metric in metrics:
                    if pd.isna(row[metric]):
                        cells.append("--")
                        continue
                    text = cell(row, metric)
                    top, value, spread = best[metric]
                    eligible = metric != "fired_before_frontier" or row["detection_rate"] >= 0.9
                    own = row.get(f"{metric}_std", 0)
                    if name == top:
                        text = rf"$\mathbf{{{text.strip('$')}}}$"
                    elif eligible and abs(value - row[metric]) <= max(spread, 0 if pd.isna(own) else own):
                        text = rf"\underline{{{text}}}"
                    if metric == "fired_before_frontier" and row["detection_rate"] < 0.9:
                        text += r"$^\dagger$"
                    cells.append(text)
                lines.append("    " + " & ".join(cells) + r" \\")
    return rf"""\begin{{table}}[!htbp]
  \centering
  \caption{{{caption}}}
  \label{{{label}}}
  \footnotesize
  \setlength{{\tabcolsep}}{{4pt}}
  \begin{{tabular}}{{llrrr}}
    \toprule
    Model & Scorer & Post & $\mathrm{{Warn}}_{{256}}$ & Early \\
    \midrule
{chr(10).join(lines)}
    \bottomrule
  \end{{tabular}}
\end{{table}}
"""


def comparison_full_table(budget: float, split: str, label: str, caption: str) -> str:
    """Every scorer with all seven metrics, one block per model."""
    rows = comparison_rows(budget, split, "own")
    same = comparison_rows(budget, split, "same")
    lines = []
    for model, picked in rows.items():
        if lines:
            lines.append(r"    \midrule")
        ordered = [(SCORER_NAMES[n], picked.get(n)) for _, names in SCORER_GROUPS for n in names if n != "adapted probe"]
        frozen_layer, adapted_layer = PROBES[model][0][1], PROBES[model][-1][1]
        ordered[-1] = (f"frozen probe, L{frozen_layer}", ordered[-1][1])
        ordered += [(f"adapted probe, L{frozen_layer}", same[model].get("adapted probe")),
                    (f"adapted probe, L{adapted_layer}", picked.get("adapted probe"))]
        positives = None
        for i, (name, row) in enumerate(ordered):
            if row is None:
                continue
            fa = {**row, "negative_fpr": row["negative_fpr"] * 100, "negative_fpr_std": row.get("negative_fpr_std", np.nan) * 100}
            lead = row["median_offset"]
            lead_text = "--" if pd.isna(lead) else (f"${lead:+.0f}$" if row["seeds"] < 2 or pd.isna(row["median_offset_std"])
                                                    else f"${lead:+.0f}\\sd{{{row['median_offset_std']:.0f}}}$")
            cells = [MODELS[model][1] if i == 0 else "", name, cell(fa, "negative_fpr", 1), cell(row, "detection_rate", 2),
                     f"${row['rollout_auc']:.4f}$" if pd.notna(row["rollout_auc"]) else "--",
                     cell(row, "in_pattern_recall"), cell(row, "warning_recall_256"), cell(row, "preonset_coverage_256"),
                     cell(row, "fired_before_frontier") if pd.notna(row["fired_before_frontier"]) else "--", lead_text]
            lines.append("    " + " & ".join(cells) + r" \\")
    return rf"""\begin{{table}}[!htbp]
  \centering
  \caption{{{caption}}}
  \label{{{label}}}
  \scriptsize
  \setlength{{\tabcolsep}}{{1.9pt}}
  \begin{{tabular}}{{llrrrrrrrr}}
    \toprule
    Model & Scorer & FA (\%) & Detection & AUROC & Post & $\mathrm{{Warn}}_{{256}}$ & Pre & Early & Lead \\
    \midrule
{chr(10).join(lines)}
    \bottomrule
  \end{{tabular}}
\end{{table}}
"""


