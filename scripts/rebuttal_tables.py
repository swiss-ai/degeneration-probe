def per_source_metrics(table: pd.DataFrame, budget: float) -> pd.DataFrame:
    """Warning coverage and early-warning rate of the frozen and own-layer adapted probes, per source and seed,
    from the per-response evaluation tables."""
    s4 = table[table["recipe"].str.startswith("frontier_window W=512 centered K=256")].copy()
    s4["regime"] = np.where(s4["lora"].eq("none"), "frozen", "adapted")
    out = []
    for model, probes in PROBES.items():
        for regime, layer in (probes[0], probes[2]):
            for split, _ in SOURCES:
                rows = s4[(s4["model"] == model) & (s4["regime"] == regime) & (s4["layer"] == layer)
                          & (s4["split"] == split) & np.isclose(s4["target_negative_fpr"], budget)]
                for scorer_dir in rows["scorer_dir"]:
                    responses = pd.read_csv(f"{scorer_dir}/evaluation/{split}/rollout_table.csv")
                    responses = responses[np.isclose(responses["target_negative_fpr"], budget)]
                    for source, group in responses.groupby("domain"):
                        positive = group[group["is_positive"].astype(bool)]
                        fired = positive[positive["fired"].astype(bool)]
                        out.append({"model": model, "regime": regime, "source": source, "positives": len(positive),
                                    "warn": positive["warning_hits_256"].sum() / max(positive["warning_tokens_256"].sum(), 1),
                                    "early": (fired["offset"] < 0).mean() if len(fired) else np.nan})
    return pd.DataFrame(out).groupby(["model", "regime", "source"]).mean().reset_index()


def per_source_table(table: pd.DataFrame, budget: float) -> str:
    frame = per_source_metrics(table, budget).set_index(["model", "regime", "source"])
    blocks = []
    for metric, title in (("warn", r"Warning coverage $\mathrm{Warn}_{256}$"), ("early", "Early-warning rate")):
        lines = [rf"\multicolumn{{10}}{{l}}{{\textbf{{{title}}}}} \\"]
        for i, (split, sources) in enumerate(SOURCES):
            if i:
                lines.append(r"\addlinespace[2pt]")
            for source in sources:
                cells = [r"\texttt{" + source.replace("_", r"\_") + "}"]
                for model in PROBES:
                    n = int(frame.loc[(model, "frozen", source), "positives"])
                    cells.append(str(n))
                    for regime in ("frozen", "adapted"):
                        value = frame.loc[(model, regime, source), metric]
                        cells.append("--" if n < MIN_SOURCE_POSITIVES or pd.isna(value) else f"{value:.2f}")
                lines.append(" & ".join(cells) + r" \\")
