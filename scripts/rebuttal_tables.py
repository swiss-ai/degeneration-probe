def small(value):
    """Three decimals, or one significant digit for a nonzero value that would print as zero."""
    if pd.isna(value):
        return "--"
    if 0 < abs(value) < 0.0005:
        return f"{value:.{int(-np.floor(np.log10(abs(value))))}f}"
    return f"{value:.3f}"


def pm(mean, std, digits):
    if pd.isna(mean):
        return "--"
    if pd.isna(std):
        return f"${mean:.{digits}f}$"
    return f"${mean:.{digits}f} \\pm {std:.{digits}f}$"


