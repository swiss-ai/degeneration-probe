def rank_table(table: pd.DataFrame, split: str, budget: float) -> str:
    apertus = table[(table["model"] == "apertus") & np.isclose(table["target_negative_fpr"], budget) & table["selectable"]]
    cols = {"AUROC": "rollout_auc", "Best accuracy": "best_accuracy", r"$\mathrm{Warn}_{256}$": "warning_recall_256", "Post": "in_pattern_recall"}
    means = apertus.groupby(["recipe", "layer", "split"])[list(cols.values())].mean().reset_index()
    chosen = means[means["split"] == "val"].sort_values("warning_recall_256", ascending=False).groupby("recipe").head(1)[["recipe", "layer"]]
    both = chosen.merge(means, on=["recipe", "layer"]).pivot_table(index=["recipe", "layer"], columns="split", values=list(cols.values()))
    rows, n = [], 0
    for name, c in cols.items():
        v, t, w = both[(c, "val")], both[(c, split)], both[("warning_recall_256", split)]
        ok = v.notna() & t.notna() & w.notna()
        n = max(n, int(ok.sum()))
        rows.append((name, kendalltau(v[ok], t[ok]).statistic, kendalltau(v[ok], w[ok]).statistic))
    best = max(r[2] for r in rows)
    lines = []
    for i, (name, own, warn) in enumerate(rows):
        if i == 2:
            lines.append(r"    \midrule")
        cell = f"${warn:+.2f}$" if warn != best else f"$\\mathbf{{{warn:+.2f}}}$"
        lines.append(f"    {name} & ${own:+.2f}$ & {cell} \\\\")
    return rf"""\begin{{table}}[!htbp]
  \centering
  \caption{{Rank transfer from validation to the {test_split_name()}, Kendall's
  $\tau$ over the ${n}$ \textsc{{Apertus}} training strategies, each read at its
  validation-selected layer, at $\beta={budget * 100:.0f}\%$. Left: whether a metric
  reproduces its own ordering. Right: whether its validation ordering predicts
  the test ordering by warning coverage.}}
  \label{{tab:rank-transfer}}
  \small
  \begin{{tabular}}{{lcc}}
    \toprule
    Ranking on validation & Reproduces itself on test & Predicts test $\mathrm{{Warn}}_{{256}}$ \\
    \midrule
{chr(10).join(lines)}
    \bottomrule
  \end{{tabular}}
\end{{table}}
"""


def persistence_table(split: str, budget: float, ms=(1, 16, 64)) -> str:
    """Warning coverage, early-warning rate, lead and post-onset coverage as m grows."""
    frame = pd.read_csv(ANALYSIS / ("persistence_sweep_human_summary.csv" if HUMAN else "persistence_sweep_summary.csv"))
    frame = frame[(frame["split"] == split) & np.isclose(frame["target_negative_fpr"], budget)]
    order = []
    for model, label in (("apertus", r"\textsc{Apertus}"), ("llama", r"\textsc{Llama}"), ("mistral", r"\textsc{Mistral}")):
        probes = [p for p in frame["probe"].unique() if p.startswith(model + " ")]
        rank = lambda p: 1 if "at frozen depth" in p else 0 if " frozen " in p else 2
        for probe in sorted(probes, key=rank):
            layer = probe.rsplit("L", 1)[1]
            name = ("frozen" if rank(probe) == 0 else "adapted") + f", L{layer}"
            order.append((label if rank(probe) == 0 else "", name, probe))
    lines = []
    for i, (label, name, probe) in enumerate(order):
        if i and label:
            lines.append(r"    \midrule")
        part = frame[frame["probe"] == probe].set_index("persistence")
        cells = [label, name]
        for column in ("in_pattern_recall_mean", "warning_recall_256_mean", "fired_before_frontier_mean", "median_offset_mean"):
            fmt = (lambda v: f"${v:+.0f}$") if column == "median_offset_mean" else (lambda v: f"{v:.3f}")
            cells += [fmt(part.loc[m, column]) if m in part.index else "--" for m in ms]
        lines.append("    " + " & ".join(cells) + r" \\")
    heads = " & ".join(f"${m}$" for m in ms)
    return rf"""\begin{{table}}[!htbp]
  \centering
  \caption{{Probes at persistence $m\in\{{{", ".join(str(m) for m in ms)}\}}$, with the threshold
  recalibrated at each $m$ for $\beta={budget * 100:.0f}\%$. {test_split_name()[0].upper() + test_split_name()[1:]}, mean over three seeds.}}
  \label{{tab:persistence}}
  \footnotesize
  \setlength{{\tabcolsep}}{{3.5pt}}
  \begin{{tabular}}{{ll ccc ccc ccc ccc}}
    \toprule
    & & \multicolumn{{3}}{{c}}{{Post}} & \multicolumn{{3}}{{c}}{{$\mathrm{{Warn}}_{{256}}$}} & \multicolumn{{3}}{{c}}{{Early}} & \multicolumn{{3}}{{c}}{{Lead}} \\
    \cmidrule(lr){{3-5}}\cmidrule(lr){{6-8}}\cmidrule(lr){{9-11}}\cmidrule(lr){{12-14}}
    Model & Probe & {heads} & {heads} & {heads} & {heads} \\
    \midrule
{chr(10).join(lines)}
    \bottomrule
  \end{{tabular}}
\end{{table}}
"""


