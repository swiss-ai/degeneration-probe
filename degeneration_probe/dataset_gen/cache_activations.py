"""Phase 3 of the dataset generation pipeline: cache per-layer, per-token hidden states.

For every ``(prompt_id, rollout_idx)`` pair already generated by
``degeneration_probe.dataset_gen.generate`` (i.e. every row of
``paths.generations_shard_path(config, domain, shard_idx)``), this module
replays the rollout through the model with **teacher forcing** -- a single
forward pass over ``prompt_tokens + generated_token_ids`` with
``output_hidden_states=True, use_cache=False`` -- and saves the completion-token
slice of every layer's hidden states to a ``.safetensors`` file.

Why teacher forcing, and why not retokenize the completion
------------------------------------------------------------
The prompt is rebuilt from ``prompts.parquet`` via the exact same chat-template
path ``generate.py`` used to produce it
(:func:`degeneration_probe.dataset_gen.generate.build_generation_prompt`), so
re-tokenizing it here reproduces the same prompt token ids deterministically.

The completion is different: ``generate.py`` already stored the exact sampled
token ids (``generated_token_ids``) for every rollout. Re-tokenizing
``generated_text`` instead (encode(decode(ids))) is not guaranteed to round-trip
to the same ids for all tokenizers/strings (whitespace/merge ambiguities can
make it lossy), which would silently misalign the activations we extract here
against labels (entropy, TTR, LRS, ...) computed elsewhere directly on
``generated_token_ids``. So this module *never* retokenizes the completion --
it concatenates ``generated_token_ids`` directly onto the freshly retokenized
prompt ids and feeds the whole thing through one forward pass.

Hidden state layout
--------------------
``model(..., output_hidden_states=True)`` returns a tuple of
``num_hidden_layers + 1`` tensors: ``hidden_states[0]`` is the embedding
output, ``hidden_states[i + 1]`` is decoder block ``i``'s output (see
``scripts/extract_traj_activations.py`` for the single-example version this
generalizes). For Apertus-8B-Instruct-2509 (32 layers) that is 33 tensors.
Only the completion-token positions (``[prompt_len : prompt_len +
completion_len]``) are kept from every layer, stacked into a single
``[num_layers + 1, completion_len, hidden_size]`` tensor, cast to float16, and
saved as one ``"hidden_states"`` tensor per ``.safetensors`` file (see
``paths.rollout_activation_path``).

Resumability
------------
Before processing any ``(prompt_id, rollout_idx)``, the activations manifest
(``paths.activations_manifest_path``) is checked; rows already recorded with
``status == "ok"`` are skipped. After every single rollout (batch size is
always 1 here -- see the module-level note below), the in-memory manifest
dataframe is updated and rewritten to disk via the same temp-file +
``os.replace`` atomic pattern ``generate.py`` uses for its shard parquets
(:func:`degeneration_probe.dataset_gen.generate.write_shard_atomic`, reused
directly here since it is generic over any dataframe/path). The safetensors
file for a given rollout is written the same way (temp file in the same
directory, then ``os.replace``), so a crash mid-write can never leave a
corrupt/partial ``.safetensors`` file or a corrupt manifest -- at most the
in-flight rollout needs to be recomputed on the next run.

A rollout that raises during processing (e.g. an OOM) is recorded in the
manifest with ``status == "failed"`` and its exception message, rather than
crashing the whole run; a fresh run will retry any ``"failed"`` row (only
``"ok"`` rows are skipped).

Batching
--------
Batch size is always 1: a full sequence (prompt + up to ``max_new_tokens``
completion tokens) x (num_hidden_layers + 1) x hidden_size in float16 is
already substantial per-row memory, and correctness/resumability matter far
more than throughput for this phase (see the task instructions this module
was written against). Do not batch multiple rollouts into one forward pass
without re-deriving the memory budget.
"""

from __future__ import annotations

import argparse
import os
import tempfile
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Set, Tuple

import pandas as pd
import torch
from safetensors.torch import load_file, safe_open, save_file

from degeneration_probe.dataset_gen import paths
from degeneration_probe.dataset_gen.config import DatasetGenConfig
from degeneration_probe.dataset_gen.generate import (
    build_generation_prompt,
    load_tokenizer_for_generation,
    write_shard_atomic,
)

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_CONFIG_PATH = REPO_ROOT / "configs" / "dataset" / "builds" / "degeneration-dataset-apertus-8b-instruct.yaml"

Task = Tuple[str, int]  # (prompt_id, rollout_idx)

ACTIVATIONS_MANIFEST_COLUMNS = [
    "prompt_id",
    "rollout_idx",
    "domain",
    "path",
    "shape",
    "dtype",
    "status",
    "error_message",
]

LAYER_ORDER_LABEL = "embedding_then_blocks_0..31"


# --- chat templating / tokenization ------------------------------------------

def tokenize_no_special(tokenizer, text: str) -> List[int]:
    """Tokenize ``text`` without adding any special tokens (mirrors
    ``scripts/extract_traj_activations.py``'s helper of the same name)."""
    return tokenizer(text, add_special_tokens=False, return_attention_mask=False)["input_ids"]


def build_completion_input_ids(
    tokenizer, prompt_text: str, generated_token_ids: Sequence[int]
) -> Tuple[List[int], int]:
    """Reconstruct ``prompt_tokens + generated_token_ids`` for one rollout.

    The prompt is retokenized via ``build_generation_prompt`` (same
    chat-template path ``generate.py`` used when producing the rollout).
    ``generated_token_ids`` is used verbatim -- never retokenized -- see the
    module docstring for why. Returns ``(input_ids, prompt_len)``.
    """
    prompt_rendered = build_generation_prompt(tokenizer, prompt_text)
    prompt_ids = tokenize_no_special(tokenizer, prompt_rendered)
    input_ids = list(prompt_ids) + list(generated_token_ids)
    return input_ids, len(prompt_ids)


# --- forward pass / activation extraction ------------------------------------

def extract_completion_hidden_states(
    model, input_ids: Sequence[int], prompt_len: int, completion_len: int, device: torch.device
) -> torch.Tensor:
    """Teacher-forced forward pass; returns completion-only hidden states.

    Shape ``[num_hidden_layers + 1, completion_len, hidden_size]``, float16,
    on CPU. Layer 0 is the embedding output; layer i+1 is decoder block i's
    output (see module docstring).
    """
    input_ids_t = torch.tensor([list(input_ids)], dtype=torch.long, device=device)
    with torch.no_grad():
        out = model(input_ids_t, output_hidden_states=True, use_cache=False)
    hidden_states = out.hidden_states  # tuple of (num_hidden_layers + 1) tensors
    completion_slice = slice(prompt_len, prompt_len + completion_len)
    stacked = torch.stack([hs[0, completion_slice] for hs in hidden_states], dim=0)
    return stacked.to(torch.float16).cpu()


# --- safetensors read/write ---------------------------------------------------

def build_activation_metadata(prompt_id: str, rollout_idx: int, completion_len: int) -> Dict[str, str]:
    """Non-empty-string metadata dict required by safetensors' header format."""
    return {
        "prompt_id": str(prompt_id),
        "rollout_idx": str(rollout_idx),
        "completion_len": str(completion_len),
        "dtype": "float16",
        "layer_order": LAYER_ORDER_LABEL,
    }


def save_activation_file(path: Path, hidden_states: torch.Tensor, metadata: Dict[str, str]) -> None:
    """Write ``hidden_states`` (named tensor "hidden_states") atomically."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_path = tempfile.mkstemp(dir=str(path.parent), prefix=".tmp_act_", suffix=".safetensors")
    os.close(fd)
    try:
        save_file({"hidden_states": hidden_states.contiguous()}, tmp_path, metadata=metadata)
        os.replace(tmp_path, path)
    except Exception:
        if os.path.exists(tmp_path):
            os.remove(tmp_path)
        raise


def load_activation_file(path: Path) -> Tuple[torch.Tensor, Dict[str, str]]:
    """Load back a saved activation file: (hidden_states tensor, metadata dict)."""
    tensors = load_file(str(path))
    with safe_open(str(path), framework="pt") as f:
        metadata = f.metadata() or {}
    return tensors["hidden_states"], metadata


# --- activations manifest (resumability) -------------------------------------

def load_existing_activations_manifest(manifest_path: Path) -> pd.DataFrame:
    if manifest_path.exists():
        return pd.read_parquet(manifest_path)
    return pd.DataFrame(columns=ACTIVATIONS_MANIFEST_COLUMNS)


def ok_tasks_from_manifest(df: pd.DataFrame) -> Set[Task]:
    """(prompt_id, rollout_idx) pairs already recorded with status == 'ok'."""
    if df.empty:
        return set()
    ok = df[df["status"] == "ok"]
    return {(str(pid), int(ridx)) for pid, ridx in zip(ok["prompt_id"], ok["rollout_idx"])}


def upsert_manifest_row(df: pd.DataFrame, row: Dict) -> pd.DataFrame:
    """Append ``row`` to ``df``, keeping the newest entry per (prompt_id, rollout_idx)."""
    new_df = pd.DataFrame.from_records([row], columns=ACTIVATIONS_MANIFEST_COLUMNS)
    combined = pd.concat([df, new_df], ignore_index=True)
    return combined.drop_duplicates(subset=["prompt_id", "rollout_idx"], keep="last")


def write_activations_manifest_atomic(df: pd.DataFrame, manifest_path: Path) -> None:
    # Generic over any (dataframe, path) pair -- reuse generate.py's atomic
    # shard-write helper verbatim rather than duplicating the temp+replace logic.
    write_shard_atomic(df, manifest_path)


# --- per-rollout processing ----------------------------------------------------

def process_task(
    config: DatasetGenConfig,
    model,
    tokenizer,
    domain: str,
    prompt_id: str,
    rollout_idx: int,
    prompt_text: str,
    generated_token_ids: Sequence[int],
    device: torch.device,
) -> Dict:
    """Run one (prompt_id, rollout_idx) through the model and save its activations.

    Returns the manifest row dict (status "ok" or "failed" -- never raises;
    failures are captured so one bad rollout doesn't abort the whole run).
    """
    out_path = paths.rollout_activation_path(config, domain, prompt_id, rollout_idx)
    try:
        input_ids, prompt_len = build_completion_input_ids(tokenizer, prompt_text, generated_token_ids)
        completion_len = len(generated_token_ids)
        hidden_states = extract_completion_hidden_states(
            model, input_ids, prompt_len, completion_len, device
        )
        metadata = build_activation_metadata(prompt_id, rollout_idx, completion_len)
        save_activation_file(out_path, hidden_states, metadata)
        return {
            "prompt_id": prompt_id,
            "rollout_idx": rollout_idx,
            "domain": domain,
            "path": str(out_path),
            "shape": list(hidden_states.shape),
            "dtype": "float16",
            "status": "ok",
            "error_message": None,
        }
    except Exception as exc:  # noqa: BLE001 - deliberately broad, see docstring
        return {
            "prompt_id": prompt_id,
            "rollout_idx": rollout_idx,
            "domain": domain,
            "path": str(out_path),
            "shape": None,
            "dtype": None,
            "status": "failed",
            "error_message": f"{type(exc).__name__}: {exc}",
        }


# --- per-domain driver ---------------------------------------------------------

def run_domain(
    config: DatasetGenConfig,
    model,
    tokenizer,
    prompts_df: pd.DataFrame,
    domain: str,
    device: torch.device,
    shard_idx: int = 0,
    max_prompts: Optional[int] = None,
    max_rollouts_per_prompt: Optional[int] = None,
    prompt_ids: Optional[Sequence[str]] = None,
) -> pd.DataFrame:
    """Cache activations for every (prompt_id, rollout_idx) in one domain's shard.

    ``max_prompts`` / ``max_rollouts_per_prompt`` / ``prompt_ids`` are debug
    knobs for dry runs (cap distinct prompts, cap rollout_idx per prompt, or
    restrict to an explicit prompt_id allowlist); all default to "no limit"
    for a real full run.
    """
    manifest_path = paths.activations_manifest_path(config)
    manifest_df = load_existing_activations_manifest(manifest_path)
    ok_done = ok_tasks_from_manifest(manifest_df)

    gen_shard_path = paths.generations_shard_path(config, domain, shard_idx)
    gen_df = pd.read_parquet(gen_shard_path)

    if prompt_ids is not None:
        gen_df = gen_df[gen_df["prompt_id"].isin(set(prompt_ids))]
    elif max_prompts is not None:
        keep_ids = list(dict.fromkeys(gen_df["prompt_id"]))[:max_prompts]
        gen_df = gen_df[gen_df["prompt_id"].isin(set(keep_ids))]

    if max_rollouts_per_prompt is not None:
        gen_df = gen_df[gen_df["rollout_idx"] < max_rollouts_per_prompt]

    prompt_text_by_id = dict(zip(prompts_df["prompt_id"], prompts_df["prompt_text"]))

    all_tasks = list(zip(gen_df["prompt_id"], gen_df["rollout_idx"]))
    remaining = [t for t in all_tasks if t not in ok_done]
    print(
        f"[{domain}] {len(all_tasks)} selected tasks, {len(ok_done)} already ok "
        f"(globally), {len(remaining)} remaining",
        flush=True,
    )

    gen_lookup = gen_df.set_index(["prompt_id", "rollout_idx"], drop=False)

    for prompt_id, rollout_idx in remaining:
        row = gen_lookup.loc[(prompt_id, rollout_idx)]
        generated_token_ids = list(row["generated_token_ids"])
        prompt_text = prompt_text_by_id[prompt_id]

        result_row = process_task(
            config, model, tokenizer, domain, prompt_id, rollout_idx,
            prompt_text, generated_token_ids, device,
        )
        manifest_df = upsert_manifest_row(manifest_df, result_row)
        write_activations_manifest_atomic(manifest_df, manifest_path)

        status = result_row["status"]
        print(f"  {prompt_id} rollout_{rollout_idx}: {status}", flush=True)

    return manifest_df


# --- CLI entry point -----------------------------------------------------------

_DTYPES = {"bfloat16": torch.bfloat16, "float16": torch.float16, "float32": torch.float32}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--config", type=str, default=str(DEFAULT_CONFIG_PATH),
        help="Path to the DatasetGenConfig YAML file.",
    )
    parser.add_argument(
        "--domains", nargs="*", default=None,
        help="Subset of domains to cache (default: all configured domains).",
    )
    parser.add_argument(
        "--shard-idx", type=int, default=0,
        help="Generation shard index to read from (default: 0, the only shard today).",
    )
    parser.add_argument(
        "--max-prompts", type=int, default=None,
        help="Debug: cap number of distinct prompts per domain (for dry runs).",
    )
    parser.add_argument(
        "--max-rollouts-per-prompt", type=int, default=None,
        help="Debug: only process rollout_idx < N for each prompt (for dry runs).",
    )
    parser.add_argument(
        "--prompt-ids", nargs="*", default=None,
        help="Debug: restrict to an explicit prompt_id allowlist (for dry runs), "
        "overrides --max-prompts.",
    )
    parser.add_argument("--dtype", default="bfloat16", choices=sorted(_DTYPES))
    args = parser.parse_args()

    from transformers import AutoModelForCausalLM

    config = DatasetGenConfig.from_yaml(args.config)
    prompts_df = pd.read_parquet(paths.prompts_path(config))
    domains = args.domains or sorted(paths.configured_domain_names(config))

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    dtype = _DTYPES[args.dtype]

    tokenizer_name = config.tokenizer_name or config.model_name
    print(
        f"Loading tokenizer {tokenizer_name!r} + model {config.model_name!r} "
        f"(dtype={args.dtype}, device={device})..."
    )
    tokenizer = load_tokenizer_for_generation(config)
    model = AutoModelForCausalLM.from_pretrained(config.model_name, dtype=dtype).to(device)
    model.eval()

    for domain in domains:
        run_domain(
            config, model, tokenizer, prompts_df, domain, device,
            shard_idx=args.shard_idx,
            max_prompts=args.max_prompts,
            max_rollouts_per_prompt=args.max_rollouts_per_prompt,
            prompt_ids=args.prompt_ids,
        )


if __name__ == "__main__":
    main()
